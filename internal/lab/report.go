// Markdown renders the results table for README.md and reports/RESULTS.md.
func Markdown(main Result, other *Result) string {
	var b strings.Builder
	fmt.Fprintf(&b, "**%s split** · %d seeds × %d sites upgraded to %s · mean per seed ± 95%% interval · settings `config/lab.yaml` (sha256 `%s`)\n\n",
		main.Split, len(main.Seeds), main.SitesPerSeed, main.Target, main.ConfigSHA256[:12])
	b.WriteString("| Per 100 site upgrades |")
	for _, d := range main.Designs {
		fmt.Fprintf(&b, " %s |", d.Label)
	}
	b.WriteString("\n|---|")
	for range main.Designs {
		b.WriteString("---:|")
	}
	b.WriteString("\n")
	for _, m := range Metrics {
		label := m.Label
		if m.Unit != "per 100" {
			label += " (" + m.Unit + ")"
		}
		fmt.Fprintf(&b, "| %s |", label)
		for _, d := range main.Designs {
			s := d.Metrics[m.Key]
			cell := fmt.Sprintf("%s ± %s", num(s.Mean), num(s.CI95))
			if d.Design == Operator {
				cell = "**" + cell + "**"
			}
			fmt.Fprintf(&b, " %s |", cell)
		}
		b.WriteString("\n")
	}
	b.WriteString("| Downtime, worst 5% of upgrades (minutes) |")
	for _, d := range main.Designs {
		fmt.Fprintf(&b, " %s |", num(d.DowntimeP95))
	}
	b.WriteString("\n")
	if other != nil {
		op, base := find(*other, Operator), find(*other, Scripted)
		fmt.Fprintf(&b, "\nThe %s split (%d seeds) agrees: operator %s data-loss and %s broken sites per 100 against %s and %s for the scripted runbook.\n",
			other.Split, len(other.Seeds), num(op.Metrics["data_loss"].Mean), num(op.Metrics["broken"].Mean), num(base.Metrics["data_loss"].Mean), num(base.Metrics["broken"].Mean))
	}
	return b.String()
}

// Report is reports/RESULTS.md.
func Report(dev Result, held *Result) string {
	var b strings.Builder
	b.WriteString("# Upgrade lab results\n\n")
	b.WriteString("Generated by `go run ./cmd/lab report` from `results/*.json`. Do not edit by hand; CI regenerates it and fails on any difference.\n\n")
	b.WriteString("Every rate behind these numbers is an assumption in `config/lab.yaml`. The lab measures how the designs differ on the same luck, not how often things fail at a real customer.\n\n")
	main := dev
	if held != nil {
		main = *held
		b.WriteString("## Held-out seeds (run once, locked)\n\n")
		b.WriteString(Markdown(*held, nil))
		b.WriteString("\n## Dev seeds\n\n")
		b.WriteString(Markdown(dev, nil))
	} else {
		b.WriteString("## Dev seeds\n\n")
		b.WriteString(Markdown(dev, nil))
		b.WriteString("\nThe held-out split has not been run yet.\n")
	}
	b.WriteString("\n## What went wrong first, all seeds of the split above\n\n")
	causes := map[string]bool{}
	for _, d := range main.Designs {
		for c := range d.Causes {
			causes[c] = true
		}
	}
	keys := sortedSet(causes)
	b.WriteString("| Cause |")
	for _, d := range main.Designs {
		fmt.Fprintf(&b, " %s |", d.Label)
	}
	b.WriteString("\n|---|")
	for range main.Designs {
		b.WriteString("---:|")
	}
	b.WriteString("\n")
	for _, c := range keys {
		fmt.Fprintf(&b, "| %s |", c)
		for _, d := range main.Designs {
			fmt.Fprintf(&b, " %d |", d.Causes[c])
		}
		b.WriteString("\n")
	}
	b.WriteString("\n## Checks that stopped an upgrade before any change\n\n")
	for _, d := range main.Designs {
		if len(d.Blocks) == 0 {
			continue
		}
		parts := []string{}
		for _, k := range sortedSet(keysOf(d.Blocks)) {
			parts = append(parts, fmt.Sprintf("%s %d", k, d.Blocks[k]))
		}
		fmt.Fprintf(&b, "- %s: %s\n", d.Label, strings.Join(parts, ", "))
	}
	b.WriteString("\n## One site, five designs\n\n")
	if len(main.Example) > 0 {
		fmt.Fprintf(&b, "A site on %s whose 5.0.0 schema migration fails (first such site of seed %d):\n\n", main.Example[0].From, main.Seeds[0])
		b.WriteString("| Design | Ends on | Rollback the design ran | Downtime (min) |\n|---|---|---|---:|\n")
		for _, e := range main.Example {
			final := e.Final
			if final == "" {
				final = "broken, manual restore"
			}
			rb := strings.Join(e.Rollback, " → ")
			if rb == "" {
				rb = "–"
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", Design(e.Design).Label(), final, rb, num(e.Downtime))
		}
	}
	return b.String()
}

func find(r Result, d Design) DesignResult {
	for _, x := range r.Designs {
		if x.Design == d {
			return x
		}
	}
	return DesignResult{}
}

func num(x float64) string {
	s := fmt.Sprintf("%.1f", x)
	return strings.TrimSuffix(s, ".0")
}

func keysOf(m map[string]int) map[string]bool {
	out := map[string]bool{}
	for k := range m {
		out[k] = true
	}
	return out
}

func sortedSet(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
